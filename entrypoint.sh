#!/bin/sh
set -eu

PROXY_PORT="${PROXY_PORT:-8888}"
PROXY_BIND_IP="${PROXY_BIND_IP:-0.0.0.0}"
OUTGOING_IP="${OUTGOING_IP:-}"
ALLOWED_IPS="${ALLOWED_IPS-185.112.41.130}"
ALLOWED_TARGET_PORTS="${ALLOWED_TARGET_PORTS:-}"
ANONYMOUS_MODE="${ANONYMOUS_MODE:-false}"
BLOCK_LOCALHOST="${BLOCK_LOCALHOST:-true}"
ALLOW_ANY_IP="${ALLOW_ANY_IP:-false}"
MAX_CONN="${MAX_CONN:-2000}"
DNS_SERVERS="${DNS_SERVERS:-1.1.1.1,8.8.8.8}"
ENABLE_LOGS="${ENABLE_LOGS:-true}"
CFG_FILE="${CFG_FILE:-/tmp/3proxy.cfg}"

# Перевірка порту
case "$PROXY_PORT" in
    ''|*[!0-9]*)
        echo "[ERROR] Некоректний PROXY_PORT: '$PROXY_PORT'" >&2
        exit 1
        ;;
esac
if [ "$PROXY_PORT" -lt 1 ] || [ "$PROXY_PORT" -gt 65535 ]; then
    echo "[ERROR] PROXY_PORT має бути в діапазоні 1..65535 (отримано: $PROXY_PORT)" >&2
    exit 1
fi

# Нормалізуємо список дозволених IP (підтримуються кома, пробіл, крапка з комою, перенос рядка)
NORMALIZED_IPS="$(printf '%s' "$ALLOWED_IPS" | tr ',;\n\r\t' '     ')"

VALID_IP_COUNT=0
for ip in $NORMALIZED_IPS; do
    case "$ip" in
        *[!0-9a-fA-F.:/-]*)
            echo "[ERROR] Некоректний запис у ALLOWED_IPS: '$ip'" >&2
            exit 1
            ;;
    esac
    VALID_IP_COUNT=$((VALID_IP_COUNT + 1))
done

if [ "$VALID_IP_COUNT" -eq 0 ] && [ "$ALLOW_ANY_IP" != "true" ]; then
    echo "[ERROR] ALLOWED_IPS порожній! Щоб не запустити відкритий проксі для всього інтернету, вкажіть хоча б один IP у ALLOWED_IPS (або явно встановіть ALLOW_ANY_IP=true)." >&2
    exit 1
fi

# Генеруємо конфігурацію 3proxy
cat > "$CFG_FILE" <<EOF
# Auto-generated by entrypoint.sh
timeouts 1 5 30 60 180 1800 15 60
maxconn ${MAX_CONN}
EOF

# Налаштування DNS-резолверів та кешу
NORMALIZED_DNS="$(printf '%s' "$DNS_SERVERS" | tr ',;\n\r\t' '     ')"
if [ "$DNS_SERVERS" != "system" ] && [ -n "$NORMALIZED_DNS" ]; then
    DNS_LINES=""
    DNS_ADDED=0
    for dns in $NORMALIZED_DNS; do
        case "$dns" in
            *[!0-9a-fA-F.:]*)
                echo "[ERROR] Некоректний DNS-сервер у DNS_SERVERS: '$dns'" >&2
                exit 1
                ;;
        esac
        DNS_LINES="${DNS_LINES}nserver ${dns}
"
        DNS_ADDED=$((DNS_ADDED + 1))
    done
    if [ "$DNS_ADDED" -gt 0 ]; then
        printf 'nscache 65536\n%s' "$DNS_LINES" >> "$CFG_FILE"
    fi
fi

# Логування у stdout (перегляд через docker compose logs -f)
if [ "$ENABLE_LOGS" = "true" ]; then
    cat >> "$CFG_FILE" <<'EOF'
log
logformat "- +_L%Y-%m-%d %H:%M:%S %E client=%C:%c target=%R:%r sent=%O rcvd=%I %T"
EOF
fi

# Контроль доступу за IP-адресою клієнта (без логіна та пароля)
printf '\nauth iponly\n' >> "$CFG_FILE"

# Захист від звернень через проксі до localhost та cloud metadata самого сервера
if [ "$BLOCK_LOCALHOST" = "true" ]; then
    printf 'deny * * 127.0.0.0/8\n' >> "$CFG_FILE"
    printf 'deny * * 169.254.169.254\n' >> "$CFG_FILE"
fi

# Дозволені цільові порти (опціонально)
TARGET_PORTS_SPEC="*"
if [ -n "$ALLOWED_TARGET_PORTS" ]; then
    CLEAN_PORTS="$(printf '%s' "$ALLOWED_TARGET_PORTS" | tr -d ' \t\r\n')"
    case "$CLEAN_PORTS" in
        *[!0-9,-]*)
            echo "[ERROR] Некоректний формат ALLOWED_TARGET_PORTS: '$ALLOWED_TARGET_PORTS'" >&2
            exit 1
            ;;
    esac
    TARGET_PORTS_SPEC="$CLEAN_PORTS"
fi

# Додаємо правила allow для кожного IP / підмережі зі списку ALLOWED_IPS
if [ "$ALLOW_ANY_IP" = "true" ] && [ "$VALID_IP_COUNT" -eq 0 ]; then
    printf 'allow * * * %s\n' "$TARGET_PORTS_SPEC" >> "$CFG_FILE"
else
    for ip in $NORMALIZED_IPS; do
        printf 'allow * %s * %s\n' "$ip" "$TARGET_PORTS_SPEC" >> "$CFG_FILE"
    done
    printf 'deny *\n' >> "$CFG_FILE"
fi

# Формуємо параметри запуску HTTP/HTTPS проксі
PROXY_FLAGS="-n"
if [ "$ANONYMOUS_MODE" = "true" ]; then
    PROXY_FLAGS="${PROXY_FLAGS} -a"
fi
PROXY_FLAGS="${PROXY_FLAGS} -p${PROXY_PORT} -i${PROXY_BIND_IP}"
if [ -n "$OUTGOING_IP" ]; then
    PROXY_FLAGS="${PROXY_FLAGS} -e${OUTGOING_IP}"
fi

printf '\nproxy %s\n' "$PROXY_FLAGS" >> "$CFG_FILE"
printf 'flush\n' >> "$CFG_FILE"

echo "========================================================"
echo " verdict-proxy-service (3proxy HTTP/HTTPS)"
echo " Listen:        ${PROXY_BIND_IP}:${PROXY_PORT}"
echo " Outgoing IP:   ${OUTGOING_IP:-default}"
echo " Auth:          none (IP whitelist via auth iponly)"
echo " Mode:          $( [ "$ANONYMOUS_MODE" = "true" ] && echo "anonymous (-a)" || echo "transparent HTTP/HTTPS" )"
echo " Target ports:  ${TARGET_PORTS_SPEC}"
if [ "$ALLOW_ANY_IP" = "true" ] && [ "$VALID_IP_COUNT" -eq 0 ]; then
    echo " Allowed IPs:   ALL (ALLOW_ANY_IP=true)"
else
    echo " Allowed IPs:   $(printf '%s' "$NORMALIZED_IPS" | tr -s ' ')"
fi
echo "========================================================"

exec "${THREEPROXY_BIN:-/bin/3proxy}" "$CFG_FILE"
